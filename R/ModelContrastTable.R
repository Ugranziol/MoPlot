#' Summarize Model Variables, Families, and Contrast Matrices
#'
#' @description
#' `ModelContrastTable()` extracts model-level and variable-level information
#' from a fitted model object.
#'
#' It reports the model class, family and link function when available, number
#' of variables, dependent variable, predictors, interactions, random-effect
#' grouping variables, variable types, number of factor levels, and contrast
#' matrix types for categorical variables.
#'
#' The function is designed to work with fitted models supported by the
#' package's internal model-extraction infrastructure, including models fitted
#' with [stats::lm()], [stats::glm()], [lme4::lmer()],
#' [lme4::glmer()], [nlme::lme()], and [glmmTMB::glmmTMB()].
#'
#' @param model A fitted model object.
#'
#' @param type Character string indicating which output should be returned.
#'   Available options are:
#'   \describe{
#'     \item{`"all"`}{
#'       Returns both model-level and variable-level summaries.
#'     }
#'     \item{`"summary"`}{
#'       Returns only the model-level summary.
#'     }
#'     \item{`"x&y"`}{
#'       Returns the variable-level summary for both the dependent variable
#'       and predictors.
#'     }
#'     \item{`"x"`}{
#'       Returns only predictors.
#'     }
#'     \item{`"y"`}{
#'       Returns only the dependent variable.
#'     }
#'   }
#'
#' @details
#' Variables found in the model frame are reported in the variable-level
#' summary. In mixed-effects models, grouping variables used in the random
#' structure may therefore also appear among the predictors.
#'
#' To avoid interpreting these variables as fixed effects only, the model-level
#' summary includes a separate `"Random Effects"` row listing the grouping
#' variables used in the random-effects structure.
#'
#' The variable-level summary also contains a `Random_Effect` column that
#' indicates whether each variable is used as a random-effect grouping
#' variable.
#'
#' The function identifies the following contrast matrix types:
#' \itemize{
#'   \item `"Sum"`: sum-to-zero contrasts generated by
#'     [stats::contr.sum()].
#'   \item `"Treatment"`: treatment contrasts generated by
#'     [stats::contr.treatment()].
#'   \item `"Polynomial"`: polynomial contrasts generated by
#'     [stats::contr.poly()].
#'   \item `"Helmert"`: Helmert contrasts generated by
#'     [stats::contr.helmert()].
#'   \item `"Sliding Differences"`: sliding-difference contrasts generated by
#'     [MASS::contr.sdif()], when `MASS` is available.
#'   \item `"Reverse Helmert"`: reverse Helmert contrasts generated by
#'     [reverse_helmert()].
#'   \item `"Custom"`: any other user-defined contrast matrix.
#' }
#'
#' @return Depending on `type`, either a list of two data frames or a single
#'   data frame.
#'
#' If `type = "all"`, the function returns an object of class
#' `"model_contrast_table"` containing:
#' \describe{
#'   \item{`Model-Level Summary`}{
#'     General information about the fitted model.
#'   }
#'   \item{`Variable-Level Summary`}{
#'     Information about each variable in the model frame.
#'   }
#' }
#'
#' The model-level summary includes:
#' \itemize{
#'   \item Model class.
#'   \item Family and link function, when available.
#'   \item Number of variables.
#'   \item Number of dependent variables and predictors.
#'   \item Number of interaction terms.
#'   \item Random-effect grouping variables.
#'   \item Dependent-variable name, type, and levels.
#'   \item Predictor names, types, and levels.
#'   \item Contrast matrix types.
#' }
#'
#' The variable-level summary includes:
#' \describe{
#'   \item{`Variable`}{Variable name.}
#'   \item{`Role`}{Dependent variable or predictor.}
#'   \item{`Type`}{Primary R class of the variable.}
#'   \item{`Levels`}{
#'     Number of factor levels or `"Numeric"` for non-factor variables.
#'   }
#'   \item{`Contrast_Matrix_Type`}{
#'     Identified contrast matrix type for factor variables.
#'   }
#'   \item{`Random_Effect`}{
#'     Whether the variable is used as a random-effect grouping variable.
#'   }
#' }
#'
#' @examples
#' set.seed(1234)
#'
#' dat <- data.frame(
#'   group = factor(rep(c("A", "B", "C"), each = 20)),
#'   y = c(
#'     rnorm(20, mean = 10, sd = 2),
#'     rnorm(20, mean = 12, sd = 2),
#'     rnorm(20, mean = 15, sd = 2)
#'   )
#' )
#'
#' contrasts(dat$group) <- contr.helmert(3)
#'
#' mod <- lm(y ~ group, data = dat)
#'
#' ModelContrastTable(mod)
#' ModelContrastTable(mod, type = "x")
#'
#' # Generalized linear model
#' dat$binary_y <- rbinom(
#'   nrow(dat),
#'   size = 1,
#'   prob = 0.5
#' )
#'
#' mod_glm <- glm(
#'   binary_y ~ group,
#'   data = dat,
#'   family = binomial
#' )
#'
#' ModelContrastTable(mod_glm)
#'
#' # Mixed-effects models
#' \dontrun{
#' library(lme4)
#' library(glmmTMB)
#'
#' dat_mixed <- expand.grid(
#'   id = factor(1:40),
#'   time = 1:10
#' )
#'
#' dat_mixed$group <- factor(
#'   sample(
#'     c("A", "B", "C"),
#'     nrow(dat_mixed),
#'     replace = TRUE
#'   )
#' )
#'
#' contrasts(dat_mixed$group) <- contr.sum(3)
#'
#' random_intercept <- rnorm(
#'   nlevels(dat_mixed$id),
#'   mean = 0,
#'   sd = 1
#' )
#'
#' dat_mixed$y <- 10 +
#'   0.3 * dat_mixed$time +
#'   2 * (dat_mixed$group == "B") +
#'   4 * (dat_mixed$group == "C") +
#'   random_intercept[dat_mixed$id] +
#'   rnorm(nrow(dat_mixed), 0, 2)
#'
#' mod_lmer <- lmer(
#'   y ~ group * time + (1 | id),
#'   data = dat_mixed
#' )
#'
#' ModelContrastTable(mod_lmer)
#'
#' eta_count <- 1 +
#'   0.1 * dat_mixed$time +
#'   0.3 * (dat_mixed$group == "B") +
#'   0.6 * (dat_mixed$group == "C") +
#'   random_intercept[dat_mixed$id]
#'
#' dat_mixed$count <- rpois(
#'   nrow(dat_mixed),
#'   lambda = exp(eta_count)
#' )
#'
#' mod_tmb <- glmmTMB(
#'   count ~ group + time + (1 | id),
#'   family = poisson,
#'   data = dat_mixed
#' )
#'
#' ModelContrastTable(mod_tmb)
#' }
#'
#' @export
ModelContrastTable <- function(model,
                               type = c(
                                 "all",
                                 "summary",
                                 "x&y",
                                 "x",
                                 "y"
                               )) {

  # ============================================================
  # 1. ARGUMENT MATCHING AND MODEL VALIDATION
  # ============================================================

  type <- match.arg(type)

  if (!.is_supported_model(model)) {

    stop(
      paste0(
        "Unsupported model class. Supported model classes include ",
        "lm, glm, lme4::lmer/glmer, lmerTest::lmer, nlme::lme, ",
        "and glmmTMB."
      ),
      call. = FALSE
    )
  }

  # ============================================================
  # 2. MODEL-LEVEL INFORMATION
  # ============================================================

  model_class <- .model_class_label(model)
  model_family <- .family_link_label(model)

  model_formula <- stats::formula(model)
  fixed_formula <- .extract_fixed_formula(model)
  terms_object <- stats::terms(fixed_formula)
  model_frame <- .extract_model_frame(model)

  random_effects <- .extract_random_effects(model)

  random_effects_label <- if (length(random_effects) == 0L) {

    NA_character_

  } else {

    paste(
      random_effects,
      collapse = ", "
    )
  }

  # ============================================================
  # 3. IDENTIFY RESPONSE AND PREDICTOR VARIABLES
  # ============================================================

  response_variables <- all.vars(
    model_formula[[2L]]
  )

  variable_names <- names(
    model_frame
  )

  predictor_variables <- setdiff(
    variable_names,
    response_variables
  )

  predictor_terms <- attr(
    terms_object,
    "term.labels"
  )

  number_total_variables <- length(
    variable_names
  )

  number_dependent_variables <- length(
    response_variables
  )

  number_predictors <- length(
    predictor_variables
  )

  number_interactions <- sum(
    grepl(
      ":",
      predictor_terms,
      fixed = TRUE
    )
  )

  # ============================================================
  # 4. VARIABLE INFORMATION HELPERS
  # ============================================================

  get_variable_type <- function(variable) {

    class(variable)[1L]
  }


  get_variable_levels <- function(variable) {

    if (is.factor(variable)) {

      return(
        as.character(
          nlevels(variable)
        )
      )
    }

    "Numeric"
  }


  same_contrast_matrix <- function(first,
                                   second) {

    isTRUE(
      all.equal(
        unname(
          as.matrix(first)
        ),
        unname(
          as.matrix(second)
        ),
        check.attributes = FALSE
      )
    )
  }


  detect_contrast <- function(variable) {

    if (!is.factor(variable)) {
      return(NA_character_)
    }

    contrast_matrix <- stats::contrasts(variable)

    if (is.null(contrast_matrix)) {
      return(NA_character_)
    }

    number_levels <- nlevels(variable)

    is_treatment <- any(
      vapply(
        seq_len(number_levels),
        function(reference_level) {
          same_contrast_matrix(
            contrast_matrix,
            stats::contr.treatment(
              number_levels,
              base = reference_level
            )
          )
        },
        logical(1)
      )
    )

    if (is_treatment) {
      return("Treatment")
    }
    reference_contrasts <- list(
      "Sum" = stats::contr.sum(number_levels),
      "Polynomial" = stats::contr.poly(number_levels),
      "Helmert" = stats::contr.helmert(number_levels),
      "Reverse Helmert" = reverse_helmert(number_levels)
    )

    if (requireNamespace(
      "MASS",
      quietly = TRUE
    )) {
      reference_contrasts[["Sliding Differences"]] <-
        MASS::contr.sdif(number_levels)
    }

    for (contrast_name in names(reference_contrasts)) {

      if (
        same_contrast_matrix(
          contrast_matrix,
          reference_contrasts[[contrast_name]]
        )
      ) {
        return(contrast_name)
      }
    }

    "Custom"
  }

  # ============================================================
  # 5. VARIABLE-LEVEL SUMMARY
  # ============================================================

  variable_types <- vapply(
    model_frame[variable_names],
    get_variable_type,
    character(1)
  )

  variable_levels <- vapply(
    model_frame[variable_names],
    get_variable_levels,
    character(1)
  )

  contrast_types <- vapply(
    model_frame[variable_names],
    detect_contrast,
    character(1)
  )

  variable_table <- data.frame(
    Variable = variable_names,
    Role = ifelse(
      variable_names %in% response_variables,
      "Dependent",
      "Predictor"
    ),
    Type = unname(
      variable_types
    ),
    Levels = unname(
      variable_levels
    ),
    Contrast_Matrix_Type = unname(
      contrast_types
    ),
    Random_Effect = variable_names %in%
      random_effects,
    stringsAsFactors = FALSE,
    row.names = NULL
  )

  # ============================================================
  # 6. MODEL-LEVEL CONTRAST SUMMARY
  # ============================================================

  predictor_contrast_types <- contrast_types[
    predictor_variables
  ]

  contrast_summary <- unique(
    stats::na.omit(
      predictor_contrast_types
    )
  )

  contrast_summary <- if (length(contrast_summary) == 0L) {

    NA_character_

  } else {

    paste(
      contrast_summary,
      collapse = ", "
    )
  }

  # ============================================================
  # 7. SAFE VARIABLE LOOKUPS
  # ============================================================

  response_types <- variable_types[
    response_variables[
      response_variables %in%
        names(variable_types)
    ]
  ]

  response_levels <- variable_levels[
    response_variables[
      response_variables %in%
        names(variable_levels)
    ]
  ]

  predictor_types <- variable_types[
    predictor_variables[
      predictor_variables %in%
        names(variable_types)
    ]
  ]

  predictor_levels <- variable_levels[
    predictor_variables[
      predictor_variables %in%
        names(variable_levels)
    ]
  ]

  collapse_or_na <- function(values) {

    values <- unname(values)

    if (length(values) == 0L) {
      return(NA_character_)
    }

    paste(
      values,
      collapse = ", "
    )
  }

  # ============================================================
  # 8. MODEL-LEVEL SUMMARY TABLE
  # ============================================================

  summary_table <- data.frame(
    Metric = c(
      "Model Class",
      "Family / Link",
      "Total Variables",
      "Dependent Variables",
      "Predictors",
      "Interactions",
      "Random Effects",
      "Dependent Variable Name",
      "Dependent Variable Type",
      "Dependent Variable Levels",
      "Predictor Names",
      "Predictor Types",
      "Predictor Levels",
      "Contrast Matrix Types"
    ),
    Value = c(
      model_class,
      model_family,
      as.character(
        number_total_variables
      ),
      as.character(
        number_dependent_variables
      ),
      as.character(
        number_predictors
      ),
      as.character(
        number_interactions
      ),
      random_effects_label,
      collapse_or_na(
        response_variables
      ),
      collapse_or_na(
        response_types
      ),
      collapse_or_na(
        response_levels
      ),
      collapse_or_na(
        predictor_variables
      ),
      collapse_or_na(
        predictor_types
      ),
      collapse_or_na(
        predictor_levels
      ),
      contrast_summary
    ),
    stringsAsFactors = FALSE,
    row.names = NULL
  )

  # ============================================================
  # 9. ASSIGN OUTPUT CLASSES AND RETURN REQUESTED OUTPUT
  # ============================================================

  if (type == "all") {

    output <- list(
      `Model-Level Summary` = summary_table,
      `Variable-Level Summary` = variable_table
    )

    class(output) <- c(
      "model_contrast_table",
      class(output)
    )

    return(output)
  }

  if (type == "summary") {

    class(summary_table) <- c(
      "model_contrast_summary",
      class(summary_table)
    )

    return(summary_table)
  }

  if (type == "x&y") {

    class(variable_table) <- c(
      "model_contrast_variables",
      class(variable_table)
    )

    return(variable_table)
  }

  if (type == "y") {

    output <- variable_table[
      variable_table$Role == "Dependent",
      ,
      drop = FALSE
    ]

    class(output) <- c(
      "model_contrast_variables",
      class(output)
    )

    return(output)
  }

  output <- variable_table[
    variable_table$Role == "Predictor",
    ,
    drop = FALSE
  ]

  class(output) <- c(
    "model_contrast_variables",
    class(output)
  )

  output
}
