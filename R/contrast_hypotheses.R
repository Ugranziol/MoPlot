#' Format a weighted group of factor levels
#'
#' @param weights Named numeric vector of non-negative weights summing to one.
#' @param digits Number of decimal places used for unequal weights.
#'
#' @return A character string: the level name for a single level,
#'   `"Mean(A, B)"` for equal weights, `"W(A .20, C .80)"` otherwise.
#'
#' @keywords internal
#' @noRd
.format_weighted_group <- function(weights,
                                   digits = 2L) {

  weights <- weights[weights > 0]

  if (length(weights) == 1L) {
    return(names(weights))
  }

  if (isTRUE(all.equal(unname(weights), rep(1 / length(weights), length(weights))))) {

    return(
      paste0("Mean(", paste(names(weights), collapse = ", "), ")")
    )
  }

  # Weights are below one within a group of two or more levels, so
  # the leading zero is dropped: 0.20 -> .20.
  formatted_weights <- sub("^0\\.", ".", formatC(weights, format = "f", digits = digits))

  paste0(
    "W(",
    paste(names(weights), formatted_weights, collapse = ", "),
    ")"
  )
}


#' Decompose contrast coefficients into weighted level comparisons
#'
#' Internal helper. For each contrast coefficient, returns the weighted
#' groups of levels on the positive and negative side and the scale factor
#' such that `h_j = scale * (positive_weights - negative_weights)`.
#'
#' Sum contrasts are presented as one level versus the unweighted Grand Mean
#' of all levels (overlapping groups). All other types use the unique split
#' of the hypothesis row into disjoint positive and negative groups.
#' Polynomial contrasts are classified but not decomposed, because a split
#' into positive and negative groups is not meaningful for them.
#'
#' For custom contrasts, the levels suggested by the signs of the coding
#' column are compared with the levels actually involved in the hypothesis.
#' When they differ, the comparison is flagged as divergent and a note
#' describing the estimated comparison is returned.
#'
#' @param contrast_matrix A k x (k - 1) contrast matrix with levels as row
#'   names.
#' @param level_names Optional character vector of factor levels; defaults
#'   to the row names of `contrast_matrix`.
#' @param tolerance Relative tolerance used to identify zero weights.
#'
#' @return A list with elements `type`, `reference`, `hypothesis_matrix`,
#'   and `contrasts`. The last is a list with one element per contrast
#'   containing `positive_weights`, `negative_weights` (named numeric
#'   vectors over all levels), `scale`, `positive_label`, `negative_label`,
#'   `overlapping`, `divergent`, and `note`. For polynomial contrasts,
#'   `contrasts` is `NULL`.
#'
#' @keywords internal
#' @noRd
.contrast_hypotheses <- function(contrast_matrix,
                                 level_names = rownames(contrast_matrix),
                                 tolerance = 1e-8) {

  contrast_matrix <- as.matrix(contrast_matrix)

  if (is.null(level_names)) {
    level_names <- as.character(seq_len(nrow(contrast_matrix)))
  }

  if (length(level_names) != nrow(contrast_matrix)) {

    stop(
      "The number of level names must equal the number of rows of the contrast matrix.",
      call. = FALSE
    )
  }

  rownames(contrast_matrix) <- level_names

  hypothesis_matrix <- .hypothesis_matrix(contrast_matrix, tolerance = tolerance)

  classification <- .classify_contrast(contrast_matrix, hypothesis_matrix)

  output <- list(
    type = classification$type,
    reference = classification$reference,
    hypothesis_matrix = hypothesis_matrix,
    contrasts = NULL
  )

  if (identical(classification$type, "Polynomial")) {
    return(output)
  }

  number_levels <- length(level_names)

  output$contrasts <- lapply(
    seq_len(nrow(hypothesis_matrix)),
    function(contrast_index) {

      hypothesis_row <- hypothesis_matrix[contrast_index, ]

      if (identical(classification$type, "Sum")) {

        # h_j = s (e_i - 1/k): level i versus the Grand Mean.
        focal_level <- which.max(hypothesis_row)

        # The focal weight is s (1 - 1/k).
        scale <- hypothesis_row[[focal_level]] * number_levels / (number_levels - 1)

        positive_weights <- stats::setNames(numeric(number_levels), level_names)
        positive_weights[focal_level] <- 1

        negative_weights <- stats::setNames(rep(1 / number_levels, number_levels), level_names)

        positive_label <- level_names[focal_level]
        negative_label <- "Grand Mean"
        overlapping <- TRUE

      } else {

        scale <- sum(hypothesis_row[hypothesis_row > 0])

        positive_weights <- stats::setNames(pmax(hypothesis_row, 0) / scale, level_names)
        negative_weights <- stats::setNames(pmax(-hypothesis_row, 0) / scale, level_names)

        positive_label <- .format_weighted_group(positive_weights)
        negative_label <- .format_weighted_group(negative_weights)
        overlapping <- FALSE
      }

      # The presentation must reconstruct the hypothesis row exactly.
      reconstructed_row <- scale * (positive_weights - negative_weights)

      if (max(abs(reconstructed_row - hypothesis_row)) > tolerance * max(abs(hypothesis_row))) {

        stop(
          paste0(
            "Internal error: the decomposition of contrast ",
            contrast_index,
            " does not reconstruct its hypothesis row."
          ),
          call. = FALSE
        )
      }

      # Compare the levels suggested by the coding column with the
      # levels actually involved in the hypothesis. Only custom
      # matrices are checked: for the recognized types the coding
      # signs are known not to describe the comparison (e.g. treatment
      # columns contain no negative weight) and the presentation is
      # documented for each type.
      divergent <- FALSE
      note <- NA_character_

      if (identical(classification$type, "Custom")) {

        coding_column <- contrast_matrix[, contrast_index]

        suggested_positive <- level_names[coding_column > 0]
        suggested_negative <- level_names[coding_column < 0]

        divergent <- !setequal(suggested_positive, level_names[positive_weights > 0]) ||
          !setequal(suggested_negative, level_names[negative_weights > 0])

        if (divergent) {

          note <- paste0(
            "Contrast_", contrast_index, ": the coding column suggests ",
            .describe_level_set(suggested_positive), " vs ",
            .describe_level_set(suggested_negative),
            ", but because the coding is not orthogonal the coefficient estimates ",
            formatC(scale, format = "fg", digits = 3), " x [",
            positive_label, " - ", negative_label, "]."
          )
        }
      }

      list(
        positive_weights = positive_weights,
        negative_weights = negative_weights,
        scale = scale,
        positive_label = positive_label,
        negative_label = negative_label,
        overlapping = overlapping,
        divergent = divergent,
        note = note
      )
    }
  )

  names(output$contrasts) <- rownames(hypothesis_matrix)

  output
}


#' Format scale factors for captions
#'
#' Simple fractions such as 1/3 are shown as fractions; other values are
#' shown with three significant digits.
#'
#' @keywords internal
#' @noRd
.format_scale_factor <- function(scale_factors) {

  vapply(
    scale_factors,
    function(value) {

      fraction <- as.character(MASS::fractions(value, max.denominator = 20L))

      parts <- as.numeric(strsplit(fraction, "/", fixed = TRUE)[[1L]])

      approximation <- if (length(parts) == 2L) parts[1L] / parts[2L] else parts[1L]

      if (abs(approximation - value) < 1e-8) {
        return(fraction)
      }

      formatC(value, format = "fg", digits = 3)
    },
    character(1)
  )
}


#' Describe a set of levels suggested by a coding column
#'
#' @keywords internal
#' @noRd
.describe_level_set <- function(levels) {

  if (length(levels) == 0L) {
    return("(none)")
  }

  if (length(levels) == 1L) {
    return(levels)
  }

  paste0("Mean(", paste(levels, collapse = ", "), ")")
}


#' Check that displayed comparisons reconstruct the model coefficients
#'
#' Internal helper. Verifies `beta_j = scale_j * (sum(w_plus * eta) -
#' sum(w_minus * eta))` for each contrast, where `eta` are level-specific
#' predictions on the linear-predictor scale. The identity is exact for
#' additive models on the link scale, whatever values the other predictors
#' are fixed at, because each hypothesis row sums to zero.
#'
#' @param hypotheses Output of `.contrast_hypotheses()`.
#' @param coefficients Numeric vector of the focal contrast coefficients,
#'   in the order of the contrast columns.
#' @param level_values Numeric vector of link-scale level predictions, in
#'   the order of the factor levels.
#' @param tolerance Relative tolerance.
#'
#' @return A logical vector, one element per contrast.
#'
#' @keywords internal
#' @noRd
.check_hypothesis_identity <- function(hypotheses,
                                       coefficients,
                                       level_values,
                                       tolerance = 1e-6) {

  if (is.null(hypotheses$contrasts)) {

    implied <- as.numeric(hypotheses$hypothesis_matrix %*% level_values)

  } else {

    implied <- vapply(
      hypotheses$contrasts,
      function(contrast) {
        contrast$scale * sum((contrast$positive_weights - contrast$negative_weights) * level_values)
      },
      numeric(1)
    )
  }

  coefficients <- as.numeric(coefficients)

  abs(implied - coefficients) <= tolerance * pmax(1, abs(coefficients))
}
