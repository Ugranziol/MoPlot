# ============================================================
# CONTRAST HYPOTHESES
# ============================================================
#
# A contrast (coding) matrix C describes how a factor is coded in
# the model. It does not, in general, describe what the estimated
# coefficients compare. For a factor with k levels and k - 1
# contrasts, the cell means satisfy
#
#   mu = X_C beta,   X_C = [1, C],
#
# so that
#
#   beta = H mu,     H = X_C^{-1}.
#
# Row j + 1 of H (the hypothesis row h_j) states the combination
# of cell means estimated by the j-th contrast coefficient. These
# helpers make H the single source of truth for interpreting
# contrasts. The contrast type is used only to choose a readable
# presentation, which must reconstruct h_j exactly.
#
# Every non-intercept row of H sums to zero, because H %*% 1 is
# the first unit vector. Each row can therefore be written as
#
#   h_j = s_j (w_plus - w_minus),
#
# where w_plus and w_minus are weight vectors summing to one and
# s_j > 0 is a scale factor. Then
#
#   beta_j = s_j (sum(w_plus * mu) - sum(w_minus * mu)).
# ============================================================


#' Hypothesis matrix implied by a contrast matrix
#'
#' Internal helper. Inverts `[1, C]` to obtain the combination of cell
#' means estimated by each contrast coefficient.
#'
#' @param contrast_matrix A k x (k - 1) contrast (coding) matrix.
#' @param tolerance Relative tolerance below which weights are set to zero.
#'
#' @return A (k - 1) x k matrix whose rows are the hypothesis rows of the
#'   contrast coefficients and whose columns correspond to factor levels.
#'
#' @keywords internal
#' @noRd
.hypothesis_matrix <- function(contrast_matrix,
                               tolerance = 1e-8) {

  contrast_matrix <- as.matrix(contrast_matrix)

  if (!is.numeric(contrast_matrix) ||
      anyNA(contrast_matrix)) {

    stop(
      "The contrast matrix must be numeric and must not contain missing values.",
      call. = FALSE
    )
  }

  number_levels <- nrow(contrast_matrix)

  if (ncol(contrast_matrix) != number_levels - 1L) {

    stop(
      paste0(
        "The contrast matrix must have k - 1 = ",
        number_levels - 1L,
        " columns for a factor with ",
        number_levels,
        " levels; it has ",
        ncol(contrast_matrix),
        "."
      ),
      call. = FALSE
    )
  }

  coding_matrix <- cbind(1, unname(contrast_matrix))

  if (qr(coding_matrix)$rank < number_levels) {

    stop(
      paste0(
        "The contrast coding is not full rank: the intercept and the ",
        "contrast columns are linearly dependent, so the coefficients ",
        "do not identify unique comparisons between levels."
      ),
      call. = FALSE
    )
  }

  hypothesis_matrix <- solve(coding_matrix)[-1L, , drop = FALSE]

  # solve() leaves numerical residues (e.g. 1e-17) where the exact
  # weight is zero. They would otherwise add spurious levels to the
  # positive or negative side of a contrast.
  hypothesis_matrix[abs(hypothesis_matrix) < tolerance * max(abs(hypothesis_matrix))] <- 0

  level_names <- rownames(contrast_matrix)

  if (is.null(level_names)) {
    level_names <- as.character(seq_len(number_levels))
  }

  contrast_names <- colnames(contrast_matrix)

  if (is.null(contrast_names)) {
    contrast_names <- as.character(seq_len(number_levels - 1L))
  }

  dimnames(hypothesis_matrix) <- list(contrast_names, level_names)

  hypothesis_matrix
}


