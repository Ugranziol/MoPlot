#' Is a vector a positive multiple of a target pattern?
#'
#' @keywords internal
#' @noRd
.is_positive_multiple <- function(values,
                                  pattern,
                                  tolerance = 1e-8) {

  scale <- sum(values * pattern) / sum(pattern * pattern)

  scale > 0 &&
    max(abs(values - scale * pattern)) <= tolerance * max(abs(values))
}


#' Classify a contrast matrix
#'
#' Internal helper shared by the package functions. Canonical matrices
#' generated by the standard contrast functions are recognized first, which
#' also resolves the ambiguities that arise with two levels. Other matrices
#' are classified from the structure of their hypothesis rows, so that, for
#' example, treatment contrasts with any reference level and sum contrasts
#' with any omitted level are recognized regardless of how they were coded.
#'
#' @param contrast_matrix A k x (k - 1) contrast matrix.
#' @param hypothesis_matrix Optional hypothesis matrix returned by
#'   `.hypothesis_matrix()`.
#'
#' @return A list with elements `type` (one of `"Treatment"`, `"Sum"`,
#'   `"Polynomial"`, `"Helmert"`, `"Reverse Helmert"`,
#'   `"Sliding Differences"`, `"Custom"`) and `reference` (the index of the
#'   reference level for treatment contrasts, otherwise `NA`).
#'
#' @keywords internal
#' @noRd
.classify_contrast <- function(contrast_matrix,
                               hypothesis_matrix = NULL) {

  contrast_matrix <- unname(as.matrix(contrast_matrix))
  number_levels <- nrow(contrast_matrix)

  same_matrix <- function(first, second) {
    identical(dim(first), dim(unname(second))) &&
      isTRUE(all.equal(first, unname(second), check.attributes = FALSE))
  }

  result <- function(type, reference = NA_integer_) {
    list(type = type, reference = reference)
  }

  # ----------------------------------------------------------
  # CANONICAL MATRICES
  # ----------------------------------------------------------

  for (reference in seq_len(number_levels)) {
    if (same_matrix(contrast_matrix, stats::contr.treatment(number_levels, base = reference))) {
      return(result("Treatment", reference))
    }
  }

  canonical_matrices <- list(
    "Sum" = stats::contr.sum(number_levels),
    "Polynomial" = stats::contr.poly(number_levels),
    "Helmert" = stats::contr.helmert(number_levels),
    "Reverse Helmert" = reverse_helmert(number_levels),
    "Sliding Differences" = MASS::contr.sdif(number_levels)
  )

  for (contrast_type in names(canonical_matrices)) {
    if (same_matrix(contrast_matrix, canonical_matrices[[contrast_type]])) {
      return(result(contrast_type))
    }
  }

  # ----------------------------------------------------------
  # STRUCTURE OF THE HYPOTHESIS ROWS
  # ----------------------------------------------------------

  if (is.null(hypothesis_matrix)) {

    hypothesis_matrix <- tryCatch(
      .hypothesis_matrix(contrast_matrix),
      error = function(e) NULL
    )
  }

  if (is.null(hypothesis_matrix)) {
    return(result("Custom"))
  }

  hypothesis_matrix <- unname(hypothesis_matrix)
  number_contrasts <- nrow(hypothesis_matrix)

  unit_vector <- function(index) {
    replace(numeric(number_levels), index, 1)
  }

  rows_match <- function(patterns) {
    all(vapply(
      seq_len(number_contrasts),
      function(row_index) {
        .is_positive_multiple(hypothesis_matrix[row_index, ], patterns[[row_index]])
      },
      logical(1)
    ))
  }

  # Treatment: every row compares one level with a common reference.
  # The rows may appear in any order.
  reference_candidates <- which(apply(hypothesis_matrix < 0, 2L, all))

  for (reference in reference_candidates) {

    focal_levels <- apply(
      hypothesis_matrix,
      1L,
      function(row) {
        positive_levels <- which(row > 0)
        if (length(positive_levels) == 1L) positive_levels else NA_integer_
      }
    )

    if (!anyNA(focal_levels) &&
        setequal(focal_levels, setdiff(seq_len(number_levels), reference)) &&
        rows_match(lapply(focal_levels, function(level) unit_vector(level) - unit_vector(reference)))) {

      return(result("Treatment", reference))
    }
  }

  # Sum: every row compares one level with the unweighted grand mean.
  # Any level may be omitted and the rows may appear in any order.
  focal_levels <- apply(hypothesis_matrix, 1L, which.max)

  if (!anyDuplicated(focal_levels) &&
      rows_match(lapply(focal_levels, function(level) unit_vector(level) - 1 / number_levels))) {

    return(result("Sum"))
  }

  # Ordered systems: the row order is part of the definition.
  helmert_patterns <- lapply(
    seq_len(number_contrasts),
    function(j) unit_vector(j + 1L) - c(rep(1 / j, j), numeric(number_levels - j))
  )

  if (rows_match(helmert_patterns)) {
    return(result("Helmert"))
  }

  reverse_helmert_patterns <- lapply(
    seq_len(number_contrasts),
    function(j) unit_vector(j) - c(numeric(j), rep(1 / (number_levels - j), number_levels - j))
  )

  if (rows_match(reverse_helmert_patterns)) {
    return(result("Reverse Helmert"))
  }

  sliding_patterns <- lapply(
    seq_len(number_contrasts),
    function(j) unit_vector(j + 1L) - unit_vector(j)
  )

  if (rows_match(sliding_patterns)) {
    return(result("Sliding Differences"))
  }

  result("Custom")
}


